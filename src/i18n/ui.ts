const dict: Record<Locale, Record<UIKey, string>> = { zh, en };

export const t = (locale: Locale, key: UIKey): string => dict[locale][key] ?? dict.en[key];

export type LocalizedText = Partial<Record<Locale, string>> | string | undefined | null;

/** Pick the string for a locale from a { zh, en } object, falling back to English then Chinese. */
export function pick(value: LocalizedText, locale: Locale): string {
  if (!value) return '';
  if (typeof value === 'string') return value;
  return value[locale] ?? value.en ?? value.zh ?? '';
}

/** Build a site URL for a locale: href('zh', 'cuts/beef') → /zh/cuts/beef/ */
export function href(locale: Locale, path = ''): string {
  const clean = path.replace(/^\/+|\/+$/g, '');
  return clean ? `/${locale}/${clean}/` : `/${locale}/`;
}

export const isLocale = (v: unknown): v is Locale => locales.includes(v as Locale);
